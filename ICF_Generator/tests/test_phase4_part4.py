def test_query_embedding_normalization_and_dimension():
    """
    Verifies that the query embedding generated by sentence-transformers has dimension 384
    and is L2-normalized (L2 norm == 1.0).
    """
    model = embedding_service.get_model()
    dim = embedding_service.get_embedding_dimension()
    assert dim == 384

    query = "What are the possible risks of the study?"
    raw_vector = model.encode([query], batch_size=1, normalize_embeddings=True)
    np_vector = np.array(raw_vector[0], dtype=np.float32)

    assert np_vector.shape == (384,)
    l2_norm = np.linalg.norm(np_vector)
    assert pytest.approx(l2_norm, abs=1e-4) == 1.0

def test_mandatory_clinical_queries():
    """
    Tests the 5 mandatory clinical protocol test queries on preloaded study NCT00081328:
    1. Purpose
    2. Eligibility requirements
    3. Treatments / interventions
    4. Risks
    5. Expected outcomes
    """
    study_loader_service.index_study_vectors("NCT00081328")
    assert vector_store_service.get_total_vectors() == 48

    test_queries = [
        "What is the purpose of this study?",
        "What are the eligibility requirements?",
        "What treatments or interventions are being studied?",
        "What are the possible risks?",
        "What are the expected outcomes?"
    ]

    for q in test_queries:
        response = search_service.search_vector_store(q, top_k=5)

        assert response.status == "success"
        assert response.query == q
        assert response.top_k == 5
        assert response.total_vectors_searched == 48
        assert response.embedding_model == "all-MiniLM-L6-v2"
        assert response.results_count == 5
        assert len(response.results) == 5

        # Verify results are ranked by reranking_score and raw similarity_score is preserved
        prev_rerank = 1.01
        sections_returned = set()
        for idx, res in enumerate(response.results):
            assert res.rank == idx + 1
            assert isinstance(res.similarity_score, float)
            assert res.reranking_score is not None
            assert res.reranking_score <= prev_rerank + 1e-4
            prev_rerank = res.reranking_score
            sections_returned.add(res.section)

            # Verify complete metadata traceability
            assert isinstance(res.vector_id, int) and 0 <= res.vector_id < 48
            assert isinstance(res.chunk_id, str) and len(res.chunk_id) > 0
            assert isinstance(res.text, str) and len(res.text) > 0
            assert res.study_id == "NCT00081328"
            assert res.source_type == "json"
            assert isinstance(res.section, str) and len(res.section) > 0
            assert isinstance(res.chunk_index, int)

        # Verify that top 5 results are diverse (not all identical eligibility section)
        assert len(sections_returned) > 1

def test_section_diversity_reranking():
    """
    Verifies that section diversity re-ranking prevents single-section domination
    while preserving raw FAISS similarity scores.
    """
    study_loader_service.index_study_vectors("NCT00081328")

    # Search with diversity enabled vs disabled
    diverse_res = search_service.search_vector_store("What are the possible risks?", top_k=5, enable_diversity=True)
    raw_res = search_service.search_vector_store("What are the possible risks?", top_k=5, enable_diversity=False)

    diverse_sections = [r.section for r in diverse_res.results]
    raw_sections = [r.section for r in raw_res.results]

    # Diversity re-ranking should yield multiple distinct sections
    assert len(set(diverse_sections)) >= 2
    # Verify raw similarity scores are preserved
    for item in diverse_res.results:
        assert 0.0 <= item.similarity_score <= 1.0
        assert item.reranking_score is not None


def test_top_k_behavior():
    """
    Verifies top_k behavior for top_k = 3, top_k = 5, top_k = 10,
    and top_k = 100 (clamped safely to total vectors present).
    """
    study_loader_service.index_study_vectors("NCT00081328") # 48 vectors

    # top_k = 3
    res_3 = search_service.search_vector_store("eligibility criteria", top_k=3)
    assert res_3.results_count == 3
    assert len(res_3.results) == 3

    # top_k = 10
    res_10 = search_service.search_vector_store("eligibility criteria", top_k=10)
    assert res_10.results_count == 10
    assert len(res_10.results) == 10

    # top_k = 100 (exceeding stored 48 vectors -> safely clamped)
    res_100 = search_service.search_vector_store("eligibility criteria", top_k=100)
    assert res_100.results_count == 48
    assert len(res_100.results) == 48
    assert res_100.top_k == 100

    # Invalid top_k
    with pytest.raises(ValueError, match="top_k must be a positive integer"):
        search_service.search_vector_store("test", top_k=0)

def test_backend_restart_and_persistent_search():
    """
    Verifies that after saving index to disk, a reloaded service instance
    executes similarity search cleanly with 100% identical results.
    """
    study_loader_service.index_study_vectors("NCT00081328")
    query = "What are the possible risks?"

    orig_response = search_service.search_vector_store(query, top_k=5)

    # Instantiate fresh VectorStoreService loading from disk
    reloaded_store = VectorStoreService(vector_store_dir=vector_store_service.vector_store_dir)
    assert reloaded_store.get_total_vectors() == 48

    # Temporarily plug reloaded store into vector_store_service for search test
    old_store = search_service
    reloaded_search_service = SearchService()

    reloaded_response = reloaded_search_service.search_vector_store(query, top_k=5)
    assert reloaded_response.results_count == 5

    # Compare top result
    assert reloaded_response.results[0].chunk_id == orig_response.results[0].chunk_id
    assert pytest.approx(reloaded_response.results[0].similarity_score, abs=1e-4) == orig_response.results[0].similarity_score
    assert reloaded_response.results[0].section == orig_response.results[0].section
